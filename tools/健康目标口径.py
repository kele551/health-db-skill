def age_from_birth(birth: str, today: date | None = None) -> int | None:
    """按生日算周岁；birth 形如 1976-06-01。"""
    if not birth:
        return None
    today = today or date.today()
    try:
        y, m, d = (int(x) for x in birth.split("-")[:3])
    except Exception:
        return None
    return today.year - y - ((today.month, today.day) < (m, d))


def resolve(age: int | None) -> dict:
    """按年龄返回目标区间；算不出年龄时按 18–64 一般成人档。"""
    if age is None:
        band = BANDS[0]
    else:
        band = next((b for b in BANDS if b["min"] <= age <= b["max"]), BANDS[0])
    return {**band, "age": age}


